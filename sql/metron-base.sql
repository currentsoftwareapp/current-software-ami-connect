CREATE TABLE IF NOT EXISTS METRON_READ_BASE (
    ORG_ID VARCHAR(16777216) NOT NULL,
    CREATED_TIME TIMESTAMP_TZ(9) NOT NULL,
    METER_ID VARCHAR(16777216) NOT NULL,
    LCD_READ VARCHAR(16777216),
    BILLING_READ VARCHAR(16777216),
    READ_DATE VARCHAR(16777216) NOT NULL,
    UNIT VARCHAR(16777216),
    REFERENCE VARCHAR(16777216),
    ACCOUNT_NAME VARCHAR(16777216),
    ADDRESS VARCHAR(16777216),
    UTILITY_DEFINED VARCHAR(16777216),
    UNIQUE (ORG_ID, METER_ID, READ_DATE)
);

CREATE TABLE IF NOT EXISTS METRON_CONDITION_BASE (
    ORG_ID VARCHAR(16777216) NOT NULL,
    CREATED_TIME TIMESTAMP_TZ(9) NOT NULL,
    METER_ID VARCHAR(16777216) NOT NULL,
    EVENT_TYPE VARCHAR(16777216) NOT NULL,
    DAY_OF_OCCURRENCE VARCHAR(16777216) NOT NULL,
    UNIQUE (ORG_ID, METER_ID, EVENT_TYPE, DAY_OF_OCCURRENCE)
);
